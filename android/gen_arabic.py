"""Regenerates the Arabic shaping tables and the parity samples for the Kotlin port.

    python android/gen_arabic.py

* core/src/main/kotlin/app/tileprint/core/ArabicTables.kt  <- letter forms + enabled ligatures of arabic_reshaper
* core/src/test/resources/arabic.txt                       <- samples with the desktop result: get_display(reshape(s))
"""
import pathlib
import arabic_reshaper
import arabic_reshaper.letters as L
import arabic_reshaper.ligatures as LG
from arabic_reshaper.reshaper_config import default_config
from bidi.algorithm import get_display

ROOT = pathlib.Path(__file__).resolve().parents[1]

def esc(s):
    return "".join(c if (32 <= ord(c) < 127 and c not in '"\\$') else f"\\u{ord(c):04x}" for c in s)

forms = lambda t: "arrayOf(" + ", ".join(f'"{esc(x)}"' for x in t) + ")"
lines = ["package app.tileprint.core", "",
         "// GENERATED by android/gen_arabic.py from arabic_reshaper (MIT). Do not edit.",
         "internal object ArabicTables {",
         "    /** letter -> [isolated, initial, medial, final]; \"\" = the form does not exist */",
         "    val letters: Map<String, Array<String>> = mapOf("]
for k, v in L.LETTERS_ARABIC.items():
    lines.append(f'        "{esc(k)}" to {forms(v)},')
lines += ["    )", "", "    /** enabled ligatures in priority order: pattern -> [isolated, initial, medial, final] */",
          "    val ligatures: List<Pair<String, Array<String>>> = listOf("]
for name, (pattern, fm) in LG.LIGATURES:
    if default_config.get(name):
        lines.append(f'        "{esc(pattern)}" to {forms(fm)},')
lines += ["    )", "}", ""]
(ROOT / "android/core/src/main/kotlin/app/tileprint/core/ArabicTables.kt").write_text("\n".join(lines), encoding="utf-8")

samples = [
 "اختبار", "ملف", "تقرير 2026", "تقرير 2026 نهائي", "الملف.pdf", "ملف final.pdf", "final ملف.pdf",
 "Report تقرير (3).pdf", "مخطط_المبنى_(نسخة 2).pdf", "نص عربي with English and 123 numbers",
 "123 رقم", "رقم 123", "رقم 12.5 سم", "المقياس ×2.50", "صفحة 5 من 24", "(قوسين) بين", "a (b) ج",
 "لا", "الله", "لأ لإ لآ", "بلا لا ولا", "مرحبا بالعالم", "كتاب الطباعة الكبيرة", "ﺑﺎﺏ", "پاکستان چای ژاله گل",
 "عَرَبِيّ مُشَكَّل", "ـــ تطويل ـــ", "تصميم-الأرضية.dwg", "مشروع/نسخة/1", "100% عربي", "a", "abc 123", "",
 "  مسافات  ", "ي ى ة ؤ ئ", "أإآ ء", "فاتورة #45", "$5 دولار", "سعر: 12,500 ريال", "ملف 1 و 2 و 3",
 "X-ray أشعة", "https://x.org رابط", "عنوان، فاصلة؛ ؟",
]
out = [f"{esc(s)}|{esc(get_display(arabic_reshaper.reshape(s)))}" for s in samples]
(ROOT / "android/core/src/test/resources/arabic.txt").write_text("\n".join(out) + "\n", encoding="utf-8")
print("letters:", len(L.LETTERS_ARABIC), "samples:", len(samples))
